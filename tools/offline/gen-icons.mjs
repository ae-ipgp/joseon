// Generates the lucide-react stand-in from react-icons/lu (offline build only).
// Run again whenever the game imports a new icon:  node gen-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const TOOLS = path.dirname(new URL(import.meta.url).pathname);
const SRC = path.resolve(TOOLS, '../../src');
const require = createRequire('/opt/npm-tools/node_modules/');
const lu = require('react-icons/lu');
const walk = (d) => fs.readdirSync(d).flatMap((f) => {
  const p = path.join(d, f);
  return fs.statSync(p).isDirectory() ? walk(p) : /\.tsx?$/.test(f) ? [p] : [];
});
const names = new Set();
for (const f of walk(SRC)) {
  const s = fs.readFileSync(f, 'utf8');
  for (const m of s.matchAll(/import\s*(?:type\s*)?\{([^}]*)\}\s*from\s*'lucide-react'/g)) {
    for (const part of m[1].split(',')) {
      const n = part.trim().split(/\s+as\s+/)[0].replace(/^type\s+/, '').trim();
      if (n && n !== 'LucideProps' && n !== 'LucideIcon') names.add(n);
    }
  }
}
const ALIAS = { House: ['LuHouse', 'LuHome'] };
const missing = [];
const lines = [];
for (const n of [...names].sort()) {
  const hit = (ALIAS[n] ?? [`Lu${n}`]).find((c) => lu[c]);
  if (!hit) { missing.push(n); lines.push(`export const ${n} = wrap(LuCircle);`); continue; }
  lines.push(`export const ${n} = wrap(${hit});`);
}
const used = [...new Set(lines.map((l) => l.match(/wrap\((\w+)\)/)[1]))];
fs.writeFileSync(path.join(TOOLS, 'shims/lucide-react.tsx'), `// Generated by gen-icons.mjs: lucide-react names drawn with react-icons/lu.
import { ${used.join(', ')} } from 'react-icons/lu';
type P = { size?: number | string; strokeWidth?: number | string; [k: string]: unknown };
const wrap = (C: any) => ({ size = 24, strokeWidth = 2, ...p }: P) => <C size={size} strokeWidth={strokeWidth} aria-hidden="true" {...p} />;
${lines.join('\n')}
`);
fs.writeFileSync(path.join(TOOLS, 'types/lucide.d.ts'), `// Generated by gen-icons.mjs.
declare module 'lucide-react' {
  export type LucideProps = { size?: number | string; strokeWidth?: number | string; className?: string; color?: string; style?: { [k: string]: string | number }; 'aria-hidden'?: boolean | 'true' | 'false'; 'aria-label'?: string };
  export type LucideIcon = (p: LucideProps) => import('react').ReactNode;
${[...names].sort().map((n) => `  export const ${n}: LucideIcon;`).join('\n')}
}
`);
console.log('icons', names.size, 'missing', missing.length ? missing.join(', ') : 'none');
